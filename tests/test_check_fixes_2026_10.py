def _two_level_cfg(lean_to=True):
    """Ex9 in miniature: level 1 at 5.0 m, level 2 at 8.0 m; with lean_to, level 1 is a lean-to roof on lines 0-1 for
    frames 0-4 only, level 2 the hall on lines 1-2 for frames 0-8."""
    lv1 = [(0, j) for j in range(5)] + [(1, j) for j in range(5)] if lean_to else \
        [(i, j) for i in (1, 2) for j in range(9)]
    lv2 = [(i, j) for i in (1, 2) for j in range(9)]
    return {"NX": 2, "NY": 8, "SX": 12000.0, "SY": 7500.0, "xcoords": [0.0, 12000.0, 36000.0],
            "heights": [5000.0, 3000.0], "present": {1: lv1, 2: lv2},
            "arch": "gable warehouse with an attached lean-to office"}


def _ex9_irregularity_pkg():
    return {"irregularity": {
        "soft_storey": {"irregular": True, "by_direction": {"X": {"soft_storey_indices": [0], "irregular": True}}},
        "vertical_geometric": {"irregular": True, "storeys": [2]}},
        "seismic_analysis": {"method": "RSA"},
        "drift_table": [{"storey": 1, "dir": "X", "limit": 0.002, "dc": 0.1345},
                        {"storey": 2, "dir": "X", "limit": 0.004, "dc": 0.0868}]}


def test_part_level_note_from_the_model():
    import report_second_wave as RS
    cfg = _two_level_cfg()
    pl = RS.part_levels(cfg)
    assert len(pl) == 1 and pl[0]["level"] == 1 and pl[0]["n_shared"] == 5 and pl[0]["n_above"] == 18
    assert pl[0]["plan_m"] == (12.0, 30.0) and pl[0]["plan_above_m"] == (24.0, 60.0)
    h = RS.part_level_note(cfg, _ex9_irregularity_pkg())
    for t in ("modelling artefact", "the lean-to roof", "5 of the 18 column positions", "12.0 m &times; 30.0 m",
              "vertical geometric row", "soft-storey row", "3.0 m above it", "response spectrum analysis",
              "0.2 % drift limit (largest ratio 0.135)"):
        assert t in h, t


